"""Storage boundary. The database stores KEYS (e.g. lectures/12/assets/ab12.mp4),
never absolute paths. Keys are generated by the server — never from a user filename.

  LocalStorage  development / single node
  S3Storage     production (any S3-compatible service); needs boto3 — NOT exercised
                by the test-suite (no boto3/network in the authoring sandbox)

Operations: put, get (to a local path), local_path (context manager giving
tools like ffmpeg a real file), exists, delete, signed_url.
"""
import contextlib
import hashlib
import hmac
import os
import shutil
import tempfile
import time
from abc import ABC, abstractmethod
from typing import Iterator, Optional, Tuple

from .errors import ValidationError

MAX_SIGNED_TTL = int(os.getenv("NOTIV_SIGNED_URL_MAX_SECONDS", "3600"))
_CT = {".mp4": "video/mp4", ".m4v": "video/mp4", ".mov": "video/quicktime", ".webm": "video/webm", ".mkv": "video/x-matroska",
       ".avi": "video/x-msvideo", ".mp3": "audio/mpeg", ".m4a": "audio/mp4", ".wav": "audio/wav", ".aac": "audio/aac",
       ".ogg": "audio/ogg", ".flac": "audio/flac", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png",
       ".webp": "image/webp", ".pdf": "application/pdf",
       ".pptx": "application/vnd.openxmlformats-officedocument.presentationml.presentation"}


class StorageError(Exception):
    """Backend failure (partial delete, unreachable bucket, ...). Message is safe to log; never contains credentials."""


def clamp_ttl(expires_in) -> int:
    """Signed-URL lifetime is always 1..NOTIV_SIGNED_URL_MAX_SECONDS (default 1 h), whatever the caller asked for."""
    try:
        v = int(expires_in)
    except (TypeError, ValueError):
        v = 900
    return max(1, min(v, MAX_SIGNED_TTL))


def content_type_for(key: str) -> str:
    """Server-decided (never user-supplied) so a stored object can't be served as HTML/SVG/JS."""
    return _CT.get(os.path.splitext(key)[1].lower(), "application/octet-stream")


def disposition_for(key: str) -> str:
    """Only media/images render inline; everything else downloads."""
    return "inline" if content_type_for(key).split("/")[0] in ("image", "video", "audio") else "attachment"


def _check_key(key: str) -> str:
    if not key or key.startswith("/") or "\\" in key or "\x00" in key or any(p in ("", ".", "..") for p in key.split("/")):
        raise ValidationError(f"invalid storage key: {key!r}")
    return key


class StorageService(ABC):
    @abstractmethod
    def put(self, key: str, source: str) -> int:
        """Store the local file at `source` under `key`. Returns size in bytes."""

    @abstractmethod
    def put_bytes(self, key: str, data: bytes) -> int: ...

    @abstractmethod
    def get(self, key: str, dest: str) -> str:
        """Copy object to local path `dest`."""

    @abstractmethod
    def read_bytes(self, key: str) -> bytes: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def delete_prefix(self, prefix: str) -> int: ...

    @abstractmethod
    def signed_url(self, key: str, expires_in: int = 900) -> str: ...

    @abstractmethod
    def iter_objects(self, prefix: str = "") -> Iterator[Tuple[str, float]]:
        """Yields (key, last_modified_epoch) for every object under `prefix` (used by orphan sweeps)."""

    def health(self) -> dict:
        """{"ok": bool, "detail": str} — cheap liveness probe for /readyz."""
        return {"ok": True, "detail": "n/a"}

    @contextlib.contextmanager
    def local_path(self, key: str):
        """A real local file for `key` (downloaded to a temp file if the
        backend isn't local). Callers must not modify it."""
        tmp = tempfile.mkdtemp(prefix="notiv-")
        try:
            yield self.get(key, os.path.join(tmp, os.path.basename(key)))
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


class LocalStorage(StorageService):
    def __init__(self, root: str, signing_secret: str = "", base_url: str = "/files"):
        self.root = os.path.abspath(root)
        os.makedirs(self.root, exist_ok=True)
        self._real_root = os.path.realpath(self.root)
        self._secret = (signing_secret or os.getenv("NOTIV_SIGNING_SECRET", "")).encode()
        self.base_url = base_url.rstrip("/")

    def _path(self, key: str) -> str:
        p = os.path.abspath(os.path.join(self.root, _check_key(key)))
        if not p.startswith(self.root + os.sep):
            raise ValidationError("key escapes storage root")
        real = os.path.realpath(p)             # a symlink planted under root must not lead outside it
        if real != self._real_root and not real.startswith(self._real_root + os.sep):
            raise ValidationError("key escapes storage root")
        return p

    def put(self, key, source):
        p = self._path(key)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        shutil.copyfile(source, p)
        return os.path.getsize(p)

    def put_bytes(self, key, data):
        p = self._path(key)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data)
        return len(data)

    def get(self, key, dest):
        os.makedirs(os.path.dirname(dest) or ".", exist_ok=True)
        shutil.copyfile(self._path(key), dest)
        return dest

    def read_bytes(self, key):
        with open(self._path(key), "rb") as f:
            return f.read()

    def exists(self, key):
        return os.path.isfile(self._path(key))

    def delete(self, key):
        try:
            os.remove(self._path(key))
        except FileNotFoundError:
            pass

    def delete_prefix(self, prefix):
        d = self._path(prefix.rstrip("/"))
        n = sum(len(f) for _, _, f in os.walk(d)) if os.path.isdir(d) else 0
        shutil.rmtree(d, ignore_errors=True)
        return n

    @contextlib.contextmanager
    def local_path(self, key):
        yield self._path(key)           # no copy needed locally
        # (read-only by contract)

    # signed URLs: HMAC over key+expiry; the HTTP layer verifies with verify_signed()
    def _sig(self, key: str, exp: int) -> str:
        if not self._secret:
            raise ValidationError("NOTIV_SIGNING_SECRET is required to sign URLs")
        return hmac.new(self._secret, f"{key}|{exp}".encode(), hashlib.sha256).hexdigest()

    def signed_url(self, key, expires_in=900):
        _check_key(key)
        exp = int(time.time()) + clamp_ttl(expires_in)
        return f"{self.base_url}/{key}?exp={exp}&sig={self._sig(key, exp)}"

    def verify_signed(self, key: str, exp, sig, now: Optional[float] = None) -> bool:
        """Never raises: any malformed input is simply 'not valid'."""
        try:
            exp = int(exp)
            _check_key(key)
            if (now if now is not None else time.time()) > exp:
                return False
            if exp - (now if now is not None else time.time()) > MAX_SIGNED_TTL + 60:      # forged far-future expiry
                return False
            return hmac.compare_digest(self._sig(key, exp), str(sig))
        except Exception:                        # noqa: BLE001
            return False

    def iter_objects(self, prefix=""):
        base = self._path(prefix.rstrip("/")) if prefix else self.root
        for d, _, files in os.walk(base):
            for f in files:
                full = os.path.join(d, f)
                if os.path.islink(full):
                    continue
                yield os.path.relpath(full, self.root).replace(os.sep, "/"), os.path.getmtime(full)

    def health(self):
        try:
            probe = os.path.join(self.root, ".healthcheck")
            with open(probe, "w") as f:
                f.write("ok")
            os.remove(probe)
            return {"ok": True, "detail": "local storage writable"}
        except OSError as e:
            return {"ok": False, "detail": f"local storage not writable ({type(e).__name__})"}


class S3Storage(StorageService):
    """S3-compatible backend (AWS S3, MinIO, R2, ...). Objects are PRIVATE: users only ever get short-lived presigned
    URLs. Server-side encryption is requested when NOTIV_S3_SSE is set (e.g. AES256 / aws:kms).

    UNVERIFIED against a real bucket in the authoring sandbox (no boto3/network). core/test_s3_integration.py runs
    against any S3-compatible endpoint when NOTIV_TEST_S3_ENDPOINT/NOTIV_TEST_S3_BUCKET are set; core/test_storage_s3_fake.py
    exercises this class's logic against an in-memory fake client (NOT a substitute for the integration test).
    """

    def __init__(self, bucket: str, prefix: str = "", endpoint_url: Optional[str] = None, client=None,
                 sse: Optional[str] = None, **client_kw):
        self.bucket, self.prefix = bucket, prefix.strip("/")
        self.sse = sse if sse is not None else (os.getenv("NOTIV_S3_SSE") or None)
        if client is not None:
            self.s3 = client                       # injected (tests)
        else:
            import boto3  # lazy: only production deployments need it
            from botocore.config import Config
            cfg = Config(retries={"max_attempts": 5, "mode": "standard"}, connect_timeout=5, read_timeout=60,
                         signature_version="s3v4", s3={"addressing_style": os.getenv("NOTIV_S3_ADDRESSING", "auto")})
            kw = dict(client_kw)
            if os.getenv("NOTIV_S3_REGION"):
                kw.setdefault("region_name", os.environ["NOTIV_S3_REGION"])
            self.s3 = boto3.client("s3", endpoint_url=endpoint_url, config=cfg, **kw)

    def _k(self, key):
        return f"{self.prefix}/{_check_key(key)}" if self.prefix else _check_key(key)

    def _extra(self, key):
        extra = {"ContentType": content_type_for(key)}
        if self.sse:
            extra["ServerSideEncryption"] = self.sse
        return extra

    def put(self, key, source):
        self.s3.upload_file(source, self.bucket, self._k(key), ExtraArgs=self._extra(key))
        return os.path.getsize(source)

    def put_bytes(self, key, data):
        self.s3.put_object(Bucket=self.bucket, Key=self._k(key), Body=data, **self._extra(key))
        return len(data)

    def get(self, key, dest):
        os.makedirs(os.path.dirname(dest) or ".", exist_ok=True)
        self.s3.download_file(self.bucket, self._k(key), dest)
        return dest

    def read_bytes(self, key):
        return self.s3.get_object(Bucket=self.bucket, Key=self._k(key))["Body"].read()

    def exists(self, key):
        try:
            self.s3.head_object(Bucket=self.bucket, Key=self._k(key))
            return True
        except Exception as e:                      # botocore ClientError (imported lazily; tests inject fakes)
            code = str(getattr(e, "response", {}).get("Error", {}).get("Code", ""))
            if code in ("404", "NoSuchKey", "NotFound"):
                return False
            raise

    def delete(self, key):
        self.s3.delete_object(Bucket=self.bucket, Key=self._k(key))

    def delete_prefix(self, prefix):
        """Deletes everything under prefix/. RAISES StorageError if any object could not be deleted (the caller keeps
        the outbox row and retries) — a partial delete is never reported as success."""
        n, token = 0, None
        while True:
            kw = {"Bucket": self.bucket, "Prefix": self._k(prefix.rstrip("/")) + "/"}
            if token:
                kw["ContinuationToken"] = token
            r = self.s3.list_objects_v2(**kw)
            objs = [{"Key": o["Key"]} for o in r.get("Contents", [])]
            if objs:
                resp = self.s3.delete_objects(Bucket=self.bucket, Delete={"Objects": objs, "Quiet": True})
                errs = resp.get("Errors") or []
                if errs:
                    raise StorageError(f"{len(errs)} object(s) failed to delete (first: {errs[0].get('Code')})")
                n += len(objs)
            if not r.get("IsTruncated"):
                return n
            token = r["NextContinuationToken"]

    def signed_url(self, key, expires_in=900):
        return self.s3.generate_presigned_url(
            "get_object", ExpiresIn=clamp_ttl(expires_in),
            Params={"Bucket": self.bucket, "Key": self._k(key), "ResponseContentType": content_type_for(key),
                    "ResponseContentDisposition": disposition_for(key)})

    def iter_objects(self, prefix=""):
        token = None
        base = (self._k(prefix.rstrip("/")) + "/") if prefix else (self.prefix + "/" if self.prefix else "")
        strip = len(self.prefix) + 1 if self.prefix else 0
        while True:
            kw = {"Bucket": self.bucket, "Prefix": base}
            if token:
                kw["ContinuationToken"] = token
            r = self.s3.list_objects_v2(**kw)
            for o in r.get("Contents", []):
                lm = o.get("LastModified")
                yield o["Key"][strip:], (lm.timestamp() if hasattr(lm, "timestamp") else float(lm or 0))
            if not r.get("IsTruncated"):
                return
            token = r["NextContinuationToken"]

    _PUBLIC_GRANTEES = ("http://acs.amazonaws.com/groups/global/AllUsers",
                        "http://acs.amazonaws.com/groups/global/AuthenticatedUsers")

    @staticmethod
    def _code(e) -> str:
        return ((getattr(e, "response", None) or {}).get("Error") or {}).get("Code", "")

    @staticmethod
    def _policy_is_public(doc: str) -> bool:
        """True if any Allow statement grants access to everyone (Principal "*" / {"AWS":"*"}) without a Condition."""
        import json as _json
        try:
            stmts = _json.loads(doc).get("Statement", [])
        except Exception:                                # noqa: BLE001 — unparseable policy: treat as unsafe
            return True
        for st in stmts if isinstance(stmts, list) else [stmts]:
            if st.get("Effect") != "Allow":
                continue
            pr = st.get("Principal")
            anyone = pr == "*" or (isinstance(pr, dict) and ("*" in (pr.get("AWS") if isinstance(pr.get("AWS"), list) else [pr.get("AWS")])))
            if anyone and not st.get("Condition"):
                return True
        return False

    def _anonymous_get_known_object(self) -> Optional[str]:
        """Writes a throw-away probe OBJECT, then requests it WITHOUT credentials. 'denied' = 401/403 (private),
        'open' = 200 (public!), None = could not tell. A denied ListBucket says nothing about OBJECT access (a bucket can
        deny listing yet allow anonymous GetObject), so the probe is on a real, known object."""
        import secrets
        import urllib.error
        import urllib.parse
        import urllib.request
        try:
            base = self.s3.meta.endpoint_url.rstrip("/")
        except Exception:                                # noqa: BLE001
            return None
        key = f".notiv-privacy-probe/{secrets.token_hex(8)}"
        try:
            self.s3.put_object(Bucket=self.bucket, Key=self._k(key), Body=b"probe")
        except Exception:                                # noqa: BLE001
            return None
        try:
            url = f"{base}/{urllib.parse.quote(self.bucket)}/{urllib.parse.quote(self._k(key))}"
            try:
                with urllib.request.urlopen(urllib.request.Request(url, method="GET"), timeout=5) as r:    # noqa: S310
                    return "open" if r.status == 200 else None
            except urllib.error.HTTPError as e:
                return "denied" if e.code in (401, 403) else None        # 404 = cannot tell (e.g. virtual-host-only endpoint)
            except Exception:                            # noqa: BLE001
                return None
        finally:
            try:
                self.s3.delete_object(Bucket=self.bucket, Key=self._k(key))
            except Exception:                            # noqa: BLE001
                pass

    def check_private(self) -> dict:
        """{"private": True|False|None, "detail": str, "evidence": [...]} — POSITIVE PROOF is required for True.
        False: any evidence of public access (public policy / ACL grant / anonymous object read succeeded).
        True only if one of:
          A) the bucket's public-access-block is FULLY enabled (all four flags); or
          B) ALL of: the policy is verified non-public (policy-status IsPublic=false, or no bucket policy exists, or a
             policy with no unconditional public Allow), the ACL is verified to have no public grants, AND an anonymous
             GET of a known private object is refused.
        Anything else (a check errored / unsupported / inconclusive) -> None = NOT proven private; callers fail closed.
        An anonymous ListBucket denial is deliberately NOT used as proof."""
        ev, public = [], []
        # ── A: public-access-block ──
        pab_ok = None
        try:
            cfg = self.s3.get_public_access_block(Bucket=self.bucket)["PublicAccessBlockConfiguration"]
            pab_ok = all(cfg.get(k) for k in ("BlockPublicAcls", "IgnorePublicAcls", "BlockPublicPolicy", "RestrictPublicBuckets"))
            ev.append("public-access-block " + ("fully enabled" if pab_ok else "NOT fully enabled"))
        except Exception as e:                           # noqa: BLE001 — MinIO & some providers don't implement it
            ev.append(f"public-access-block unavailable ({self._code(e) or type(e).__name__})")
        # ── policy ──
        policy_ok = None
        try:
            policy_ok = not self.s3.get_bucket_policy_status(Bucket=self.bucket)["PolicyStatus"].get("IsPublic")
            if not policy_ok:
                public.append("bucket policy makes the bucket public")
            else:
                ev.append("policy status: not public")
        except Exception as e:                           # noqa: BLE001
            ev.append(f"policy status unavailable ({self._code(e) or type(e).__name__})")
            try:
                doc = self.s3.get_bucket_policy(Bucket=self.bucket)["Policy"]
                policy_ok = not self._policy_is_public(doc)
                (ev if policy_ok else public).append("bucket policy " + ("has no public Allow" if policy_ok else "allows public access"))
            except Exception as e2:                      # noqa: BLE001
                if self._code(e2) == "NoSuchBucketPolicy":
                    policy_ok = True; ev.append("no bucket policy")
                else:
                    ev.append(f"bucket policy unreadable ({self._code(e2) or type(e2).__name__})")
        # ── ACL ──
        acl_ok = None
        try:
            grants = self.s3.get_bucket_acl(Bucket=self.bucket).get("Grants", [])
            if any((g.get("Grantee") or {}).get("URI") in self._PUBLIC_GRANTEES for g in grants):
                acl_ok = False; public.append("bucket ACL grants access to a public group")
            else:
                acl_ok = True; ev.append("ACL has no public grants")
        except Exception as e:                           # noqa: BLE001
            ev.append(f"ACL unreadable ({self._code(e) or type(e).__name__})")
        # ── anonymous read of a known object (only needed for proof B, but any 'open' is public evidence) ──
        probe = None
        if not public and not pab_ok:
            probe = self._anonymous_get_known_object()
            if probe == "open":
                public.append("anonymous (unsigned) read of an object succeeded")
            else:
                ev.append("anonymous object read " + ("denied" if probe == "denied" else "inconclusive"))
        if public:
            return {"private": False, "detail": "; ".join(public), "evidence": ev + public}
        if pab_ok:
            return {"private": True, "detail": "; ".join(ev), "evidence": ev}
        if policy_ok and acl_ok and probe == "denied":
            return {"private": True, "detail": "; ".join(ev), "evidence": ev}
        return {"private": None, "detail": "not proven private: " + "; ".join(ev), "evidence": ev}

    def health(self):
        try:
            self.s3.head_bucket(Bucket=self.bucket)
            return {"ok": True, "detail": "bucket reachable"}
        except Exception as e:                      # noqa: BLE001
            return {"ok": False, "detail": f"bucket unreachable ({type(e).__name__})"}
